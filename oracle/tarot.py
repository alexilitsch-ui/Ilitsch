@dataclass(frozen=True)
class Card:
    name: str
    upright: str
    reversed_: str
    arcana: str  # "Старший" или "Младший"


@dataclass(frozen=True)
class DrawnCard:
    card: Card
    reversed: bool
    position: str

    @property
    def title(self) -> str:
        return f"{self.card.name}{' (перевёрнутая)' if self.reversed else ''}"

    @property
    def meaning(self) -> str:
        return self.card.reversed_ if self.reversed else self.card.upright


def build_deck() -> list[Card]:
    deck = [Card(n, u, r, "Старший") for n, u, r in MAJOR_ARCANA]
    for suit, (element, theme) in SUITS.items():
        for rank, up, rev in RANKS:
            deck.append(Card(
                f"{rank} {suit}",
                f"{up} — в сфере: {theme} (стихия {element})",
                f"{rev} — в сфере: {theme}",
                "Младший",
            ))
    return deck


DECK = build_deck()

SPREADS = {
    "day": ["Карта дня"],
    "three": ["Прошлое", "Настоящее", "Будущее"],
    "love": ["Вы", "Партнёр", "Связь между вами", "Препятствие", "Перспектива"],
    "question": ["Суть вопроса", "Что мешает", "Что поможет", "Совет", "Вероятный исход"],
}


def _seeded_rng(*parts: object) -> random.Random:
    digest = hashlib.sha256("|".join(map(str, parts)).encode()).hexdigest()
    return random.Random(int(digest, 16))


def draw(spread: str, *, seed_parts: tuple | None = None) -> list[DrawnCard]:
    """Тянет карты для расклада. С seed_parts результат воспроизводим (например, карта дня)."""
    positions = SPREADS[spread]
    rng = _seeded_rng(*seed_parts) if seed_parts else random.SystemRandom()
    cards = rng.sample(DECK, len(positions))
    return [DrawnCard(c, rng.random() < 0.3, pos) for c, pos in zip(cards, positions)]


def card_of_the_day(name: str, birth_date: date, today: date | None = None) -> DrawnCard:
    """Одна и та же карта для человека весь день."""
    today = today or date.today()
    return draw("day", seed_parts=(name.lower().strip(), birth_date, today))[0]


def describe(cards: list[DrawnCard]) -> str:
    return "\n".join(f"• {c.position}: {c.title} — {c.meaning}" for c in cards)
